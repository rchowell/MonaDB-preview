//! Generate `src/models.rs` from `mona-types/generated/openapi.json`.
//!
//! ```bash
//! cargo run --features generate --bin generate_models
//! ```

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::PathBuf;
use std::process;

use schemars::schema::{RootSchema, Schema, SchemaObject};
use serde_json::Value;
use typify::{TypeSpace, TypeSpaceSettings};

fn main() {
    let openapi_path = env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../mona-types/generated/openapi.json")
    });

    if !openapi_path.exists() {
        eprintln!("OpenAPI spec not found at {}", openapi_path.display());
        eprintln!("Run `npm run build` in mona-types first (or pass an explicit path).");
        process::exit(1);
    }

    let openapi: Value = serde_json::from_str(
        &fs::read_to_string(&openapi_path).unwrap_or_else(|err| {
            eprintln!("failed to read {}: {err}", openapi_path.display());
            process::exit(1);
        }),
    )
    .unwrap_or_else(|err| {
        eprintln!("failed to parse {}: {err}", openapi_path.display());
        process::exit(1);
    });

    let schemas = openapi
        .pointer("/components/schemas")
        .and_then(Value::as_object)
        .unwrap_or_else(|| {
            eprintln!("no components.schemas in {}", openapi_path.display());
            process::exit(1);
        });

    let mut definitions = BTreeMap::new();
    for (name, schema) in schemas {
        definitions.insert(name.clone(), rewrite_schema(schema));
    }

    let root = RootSchema {
        meta_schema: None,
        schema: SchemaObject::default(),
        definitions: definitions
            .into_iter()
            .map(|(name, value)| {
                let schema: Schema = serde_json::from_value(value).unwrap_or_else(|err| {
                    eprintln!("schema {name} is not valid JSON Schema: {err}");
                    process::exit(1);
                });
                (name, schema)
            })
            .collect(),
    };

    let mut settings = TypeSpaceSettings::default();
    settings.with_derive("PartialEq".to_string());
    settings.with_derive("Eq".to_string());
    settings.with_struct_builder(false);

    let mut type_space = TypeSpace::new(&settings);
    type_space.add_ref_types(root.definitions).unwrap_or_else(|err| {
        eprintln!("typify failed to add schemas: {err}");
        process::exit(1);
    });

    let tokens = type_space.to_stream();
    let ast = syn::parse2(tokens).unwrap_or_else(|err| {
        eprintln!("failed to parse generated tokens: {err}");
        process::exit(1);
    });
    let body = prettyplease::unparse(&ast);

    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/models.rs");
    let contents = format!(
        "\
//! OpenAPI models for the MonaDB control plane.
//!
//! @generated by `cargo run --features generate --bin generate_models`
//! from mona-types/generated/openapi.json. Do not edit by hand.

#![allow(clippy::all)]
#![allow(rustdoc::broken_intra_doc_links)]

{body}

impl DatabaseStatus {{
    pub fn as_str(self) -> &'static str {{
        match self {{
            Self::Pending => \"pending\",
            Self::Ready => \"ready\",
            Self::Sleeping => \"sleeping\",
            Self::Error => \"error\",
        }}
    }}
}}
"
    );

    fs::write(&out, contents).unwrap_or_else(|err| {
        eprintln!("failed to write {}: {err}", out.display());
        process::exit(1);
    });

    println!("Wrote {}", out.display());
}

/// Rewrite OpenAPI component schemas into standalone JSON Schema definitions.
///
/// - `#/components/schemas/X` → `#/definitions/X`
/// - Drop `minLength` / `maxLength` so string fields stay plain `String`
///   (request validation lives in the service layer).
fn rewrite_schema(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut out = serde_json::Map::new();
            for (key, child) in map {
                if key == "minLength" || key == "maxLength" {
                    continue;
                }
                if key == "$ref" {
                    if let Value::String(reference) = child {
                        out.insert(
                            key.clone(),
                            Value::String(
                                reference.replace("#/components/schemas/", "#/definitions/"),
                            ),
                        );
                        continue;
                    }
                }
                out.insert(key.clone(), rewrite_schema(child));
            }
            Value::Object(out)
        }
        Value::Array(items) => Value::Array(items.iter().map(rewrite_schema).collect()),
        other => other.clone(),
    }
}
